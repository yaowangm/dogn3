echo "Verifying row counts..."
{
  echo "table,mysql_count,postgres_count"
  for table in article category favorite forum info_bak point_log sign_log upd_log user; do
    mysql_count=$(run_mysql -e "SELECT COUNT(*) FROM \`${table}\`")
    pg_count=$(run_psql -At -c "SELECT COUNT(*) FROM \"${table}\"")
    echo "${table},${mysql_count},${pg_count}"
    if [[ "$mysql_count" != "$pg_count" ]]; then
      echo "Row count mismatch for ${table}: MySQL=${mysql_count}, PostgreSQL=${pg_count}" >&2
      exit 1
    fi
  done
} | tee "$tmpdir/row_counts.csv"

echo "Migration completed successfully."
