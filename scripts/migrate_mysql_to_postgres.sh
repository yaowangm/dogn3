copy_table "info_bak" '"ID","name","password","state","usrlevel","Email","intro","regtime","artcount","doccount","lastlogin","lastloginip","lastOrigin","lastReship","lastPost","logincount","points","introuser","signatureid","FavoCount","logerrtime","logerrcount"' \
