  '`Id`' '`ForumId`' '`ParentId`' '`RootId`' '`OrderNum`' '`OrderNum2`' '`Level`' '`Subject`' '`Size`' '`AccessCount`' '`UserName`' '`UserId`' "$(dt_expr '`PostTime`')" '`ReplyCount`' "$(dt_expr '`ReplyTime`')" '`Type`' '`Content`' '`LinkName`' '`LinkStr`' '`ImageLink`' '`State`' '`FolderId`' '`Point`' '`SignId`'

