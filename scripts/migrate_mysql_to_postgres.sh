#!/usr/bin/env bash
set -euo pipefail

# Migrates the local MySQL database "dogn" into the local PostgreSQL database
# "dogn". This script intentionally performs writes only against PostgreSQL.
#
# Usage:
#   chmod +x migrate_mysql_to_postgres.sh
#   ./migrate_mysql_to_postgres.sh --mysql-password 'your-password' --yes
#
# Optional overrides:
#   MYSQL_USER=zqh MYSQL_DATABASE=dogn PGDATABASE=dogn ./migrate_mysql_to_postgres.sh --mysql-password 'your-password' --yes

MYSQL_USER=${MYSQL_USER:-zqh}
MYSQL_DATABASE=${MYSQL_DATABASE:-dogn}
MYSQL_CMD=${MYSQL_CMD:-"mysql -u ${MYSQL_USER} --default-character-set=utf8mb4 ${MYSQL_DATABASE}"}
PGDATABASE=${PGDATABASE:-dogn}
PSQL_CMD=${PSQL_CMD:-"psql -v ON_ERROR_STOP=1 -d ${PGDATABASE}"}
MYSQL_PASSWORD=${MYSQL_PWD:-}
confirmed=0

usage() {
  cat >&2 <<EOF
Usage:
  $0 --mysql-password PASSWORD --yes

This will DROP and recreate the migrated tables in PostgreSQL database "${PGDATABASE}".
It will read from MySQL database "${MYSQL_DATABASE}" as MySQL user "${MYSQL_USER}" and will not write to MySQL.

Options:
  --mysql-password, -p PASSWORD  MySQL password. You can also set MYSQL_PWD instead.
  --yes                         Confirm the PostgreSQL destructive migration.
  --help                        Show this help text.

Optional environment overrides:
  MYSQL_USER=zqh
  MYSQL_DATABASE=dogn
  PGDATABASE=dogn
  MYSQL_CMD='mysql -u zqh --default-character-set=utf8mb4 dogn'
  PSQL_CMD='psql -v ON_ERROR_STOP=1 -d dogn'
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --mysql-password|-p)
      if [[ $# -lt 2 ]]; then
        echo "Missing value for $1" >&2
        usage
        exit 2
      fi
      MYSQL_PASSWORD=$2
      shift 2
      ;;
    --yes)
      confirmed=1
      shift
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if [[ "$confirmed" != "1" ]]; then
  usage
  echo >&2
  echo "Run with --yes to continue." >&2
  exit 2
fi

if [[ -z "$MYSQL_PASSWORD" ]]; then
  usage
  echo >&2
  echo "Missing MySQL password. Pass --mysql-password PASSWORD or set MYSQL_PWD." >&2
  exit 2
fi

for bin in mysql psql python3; do
  if ! command -v "$bin" >/dev/null 2>&1; then
    echo "Missing required command: $bin" >&2
    exit 1
  fi
done

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT

run_psql() {
  $PSQL_CMD "$@"
}

run_mysql() {
  # --raw keeps MySQL JSON output parseable by the Python CSV bridge below.
  MYSQL_PWD=$MYSQL_PASSWORD $MYSQL_CMD --batch --raw --skip-column-names "$@"
}

dt_expr() {
  local col=$1
  printf "NULLIF(DATE_FORMAT(%s, '%%Y-%%m-%%d %%H:%%i:%%s'), '0000-00-00 00:00:00')" "$col"
}

json_to_csv() {
  python3 -c '
import json
import sys

nul_fields = 0

def csv_field(value):
    global nul_fields
    if value is None:
        return ""
    text = str(value)
    if "\x00" in text:
        nul_fields += 1
        text = text.replace("\x00", "")
    return "\"" + text.replace("\"", "\"\"") + "\""

for line_no, line in enumerate(sys.stdin, 1):
    line = line.rstrip("\n")
    if not line:
        continue
    try:
        row = json.loads(line)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"Invalid JSON from MySQL on line {line_no}: {exc}") from exc
    sys.stdout.write(",".join(csv_field(value) for value in row) + "\n")

if nul_fields:
    print(f"Warning: stripped PostgreSQL-incompatible NUL bytes from {nul_fields} field(s).", file=sys.stderr)
'
}

copy_table() {
  local table=$1
  local pg_columns=$2
  shift 2

  local query="SET SESSION time_zone = '+00:00'; SELECT JSON_ARRAY("
  local sep=""
  local expr
  for expr in "$@"; do
    query+="${sep}${expr}"
    sep=", "
  done
  query+=") FROM \`${table}\`"

  echo "Loading ${table}..."
  run_mysql -e "$query" |
    json_to_csv |
    run_psql -c "\\copy \"${table}\" (${pg_columns}) FROM STDIN WITH (FORMAT csv, NULL '')"
}

