copy_table "category" '"Id","Name","Comment","OrderId","ForumCount"' \
  '`Id`' '`Name`' '`Comment`' '`OrderId`' '`ForumCount`'

copy_table "forum" '"Id","Name","Comment","CategoryId","ArtCount","RootCount","MasterName","MasterName2","MasterName3","MasterName4","MasterId","OrderId"' \
  '`Id`' '`Name`' '`Comment`' '`CategoryId`' '`ArtCount`' '`RootCount`' '`MasterName`' '`MasterName2`' '`MasterName3`' '`MasterName4`' '`MasterId`' '`OrderId`'

copy_table "user" '"Id","Name","Password","State","Level","Email","Intro","RegTime","ArticleCount","DocCount","LastLogin","LastLoginIp","LastOrigin","LastReship","LastPost","LoginCount","Point","IntroUserId","SignId","FavoCount","LogErrTime","LogErrCount"' \
  '`Id`' '`Name`' '`Password`' '`State`' '`Level`' '`Email`' '`Intro`' "$(dt_expr '`RegTime`')" '`ArticleCount`' '`DocCount`' "$(dt_expr '`LastLogin`')" '`LastLoginIp`' "$(dt_expr '`LastOrigin`')" "$(dt_expr '`LastReship`')" "$(dt_expr '`LastPost`')" '`LoginCount`' '`Point`' '`IntroUserId`' '`SignId`' '`FavoCount`' "$(dt_expr '`LogErrTime`')" '`LogErrCount`'

